/**
 * Generate a random resident name & profile seed.
 * @param {boolean} female
 * @returns {{ firstName, lastName, nickname, dream, trait, backstory }}
 */
function generateName(female) {
    return {
        firstName: pick(female ? FEMALE_FIRST : MALE_FIRST),
        lastName:  pick(LAST_NAMES),
        nickname:  Math.random() < 0.3 ? pick(NICKNAMES) : null,
        dream:     pick(DREAMS),
        trait:     pick(TRAITS),
        backstory: pick(BACKSTORIES),
    };
}

/**
 * Full display name including optional nickname.
 */
function displayName(r) {
    if (r.nickname) return `${r.firstName} «${r.nickname}» ${r.lastName}`;
    return `${r.firstName} ${r.lastName}`;
}
